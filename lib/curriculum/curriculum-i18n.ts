/**
 * Helper to create a 13-language LocalizedString from base translations
 * Automatically populates any missing European language with a clean fallback
 */
export function L13(
  az: string,
  en: string,
  tr: string,
  ru: string,
  extra?: Partial<Record<'es' | 'de' | 'fr' | 'it' | 'pt' | 'pl' | 'cs' | 'hu' | 'uk', string>>
): LocalizedString {
  return {
    az,
    en,
    tr,
    ru,
    es: extra?.es || en,
    de: extra?.de || en,
    fr: extra?.fr || en,
    it: extra?.it || en,
    pt: extra?.pt || en,
    pl: extra?.pl || en,
    cs: extra?.cs || en,
    hu: extra?.hu || en,
    uk: extra?.uk || ru || en,
  };
}

/**
 * Gets localized curriculum UI string for any supported language (all 13 languages).
 */
export function getCurriculumText(key: CurriculumStringKey, lang: string = 'az'): string {
  const table = CURRICULUM_STRINGS[key];
  if (!table) return key;

  if (table[lang]) return table[lang];
  if (lang === 'tr') return table.tr || table.en || table.az;
  if (lang === 'az') return table.az || table.tr || table.en;
  if (lang === 'ru' || lang === 'uk') return table[lang] || table.ru || table.en;
  return table.en || table.tr || table.az || key;
}

/**
 * Returns localized text from a LocalizedString object with smart fallbacks
 * prioritizing the active user UI language across all 13 supported locales.
 */
export function getLocalizedContent(
  item: LocalizedString | undefined,
  lang: string = 'az',
  fallback: string = ''
): string {
  if (!item) return fallback;

  if (item[lang]) return item[lang]!;
  if (lang === 'tr') return item.tr || item.en || item.az || fallback;
  if (lang === 'az') return item.az || item.tr || item.en || fallback;
  if (lang === 'uk') return item.uk || item.ru || item.en || fallback;
  if (lang === 'ru') return item.ru || item.en || item.tr || item.az || fallback;
  return item.en || item.tr || item.az || fallback;
}
